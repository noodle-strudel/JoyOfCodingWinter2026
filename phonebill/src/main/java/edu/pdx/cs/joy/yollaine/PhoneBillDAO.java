  /**
   * Runs a saved database script from a file, checking first if the database is empty.
   * @param connection
   * @param dbFile
   * @throws SQLException
   */
  public static void readFrom(Connection connection, File dbFile) throws SQLException {
    DatabaseMetaData metaData = connection.getMetaData();

    // Ensure the database is completely fresh with no CUSTOMERS in it
    try (
        ResultSet tables = metaData.getTables(null, "PUBLIC", "CUSTOMERS", new String[]{"TABLE"})
    ) {
      // if it isn't then there's no work to do
      if (tables.next()) {
        String thing = tables.getString("TABLE_NAME");
        return;
      }
    }
    String readFrom = "RUNSCRIPT FROM ?";

    try (PreparedStatement statement = connection.prepareStatement(readFrom)) {
      statement.setString(1, dbFile.getAbsolutePath());
      statement.execute();
    }
  }

  /**
   * Saves a PhoneBill to the database.
   *
   * @param bill the phone bill to save
   * @throws SQLException if a database error occurs
   */
  public void save(PhoneBill bill) throws SQLException {
    // check if the phone bill already exists in the database
    // if so, check if there are any new phone calls to associate with the customer
    // don't do anything if the call already exists
    // add it in if its unique
    String customerName = bill.getCustomer();
    String checkForCustomer = "SELECT id, name from customers WHERE name = ?";

    try (PreparedStatement statement = connection.prepareStatement(checkForCustomer)) {
      statement.setString(1, customerName);
      try (ResultSet result = statement.executeQuery()) {
        if (!result.next()) {
          String insertCustomer = "INSERT INTO customers (name) VALUES (?)";

          try (PreparedStatement inStatement = connection.prepareStatement(insertCustomer)) {
            inStatement.setString(1, customerName);
            inStatement.executeUpdate();
          }
        }
      }
    }

    for (PhoneCall call: bill.getPhoneCalls()) {
      callDAO.save(call, customerName);
    }
  }

  /**
   * Finds a PhoneBill by customer name.
   *
   * @param customerName the customer name to search for
   * @return the PhoneBill for the customer, or null if not found
   * @throws SQLException if a database error occurs
   */
  public PhoneBill findByCustomerName(String customerName) throws SQLException {
    String selectCustomer = "SELECT id,name FROM customers WHERE name = ?";

    try (PreparedStatement statement = connection.prepareStatement(selectCustomer)) {
      statement.setString(1, customerName);

      return getPhoneBill(statement);
    }
  }

  /**
   * Finds a customer by its ID in the database.
   *
   * @param customerID the customer ID to search for.
   * @return the PhoneBill for the customer, or null if not found.
   * @throws SQLException if a data error occurs.
   */
  public PhoneBill findByCustomerID(int customerID) throws SQLException {
    String selectSQL = "SELECT id, name FROM customers WHERE id = ?";

    try (PreparedStatement statement = connection.prepareStatement(selectSQL)) {
      statement.setInt(1, customerID);

      return getPhoneBill(statement);
    }
  }

  @Nullable
  private PhoneBill getPhoneBill(PreparedStatement statement) throws SQLException {
    try (ResultSet resultSet = statement.executeQuery()) {
      if (!resultSet.next())
        return null;

      PhoneBill newBill;
      String name = resultSet.getString("name");
      int customerId = resultSet.getInt("id");
      newBill = new PhoneBill(name);
      for (PhoneCall call : callDAO.findCallsByCustomerID(customerId)) {
        newBill.addPhoneCall(call);
      }
      return newBill;
    }
  }

  static class PhoneCallDAO {
    private final Connection connection;

    public PhoneCallDAO(Connection connection) {
      this.connection = connection;
    }

    /**
     * Save a phone call associated with a customer if it's not already associated with the customer.
     * @param call
     * @param customerName
     * @throws SQLException
     */
    public void save(PhoneCall call, String customerName) throws SQLException {
      String checkForCall = "SELECT " +
          "caller, callee, begin_time, end_time " +
          "FROM phone_calls WHERE customer_id = (SELECT id FROM customers WHERE name = ?)";

      try (PreparedStatement checkStatement = connection.prepareStatement(checkForCall)) {
        checkStatement.setString(1, customerName);
        try (ResultSet result = checkStatement.executeQuery()) {
          boolean differentCall = true;
          while (result.next() && differentCall) {
            String caller = result.getString("caller");
            String callee = result.getString("callee");
            String beginTime = result.getTimestamp("begin_time").toLocalDateTime().format(PhoneCall.DATE_TIME_FORMAT);
            String endTime = result.getTimestamp("end_time").toLocalDateTime().format(PhoneCall.DATE_TIME_FORMAT);
            if (call.equals(new PhoneCall(caller, callee, beginTime, endTime))) {
              differentCall = false;
            }
          }

          if (differentCall) {
            String insertPhoneCall = "INSERT INTO phone_calls (" +
                "caller, callee, customer_id, begin_time, end_time" +
                ") VALUES (?, ?, (SELECT id FROM customers WHERE name = ?), ?, ?)";

            try (PreparedStatement statement = connection.prepareStatement(insertPhoneCall)) {
              statement.setString(1, call.getCaller());
              statement.setString(2, call.getCallee());
              statement.setString(3, customerName);
              statement.setTimestamp(4, Timestamp.valueOf(call.getBeginTime()));
              statement.setTimestamp(5, Timestamp.valueOf(call.getEndTime()));
              statement.executeUpdate();
            }
          }
        }
      }



    }

    public List<PhoneCall> findCallsByCustomerID(int customerID) throws SQLException {
      String selectCalls = "SELECT caller, callee, begin_time, end_time FROM phone_calls WHERE customer_id = ?";

      try (PreparedStatement statement_two = connection.prepareStatement(selectCalls)) {
        statement_two.setInt(1, customerID);
        try (ResultSet resultSet = statement_two.executeQuery()) {
          List<PhoneCall> callList = new ArrayList<>();
          while (resultSet.next()) {
            String caller = resultSet.getString("caller");
            String callee = resultSet.getString("callee");
            String beginTime = resultSet.getTimestamp("begin_time").toLocalDateTime().format(PhoneCall.DATE_TIME_FORMAT);
            String endTime = resultSet.getTimestamp("end_time").toLocalDateTime().format(PhoneCall.DATE_TIME_FORMAT);
            PhoneCall newCall = new PhoneCall(caller, callee, beginTime, endTime);
            callList.add(newCall);
          }
          return callList;
        }
      }
    }
  }

